// The short hydrogen video: frames of c11.demo.cloud playing the storyboard
// web/video/c11-hydrogen.storyboard.json in deterministic mode, captured with
// web/tools/capture/capture.ts and assembled by it with ffmpeg; captions as WebVTT from the
// same storyboard; two stills.
//
//   web/node_modules/.bin/tsx web/video/c11-video.ts [--lang de,en] [--ground light|dark] [--gl swiftshader|gl-egl|vulkan]
//        [--size 1920x1080] [--pkg 1] [--vtt-only]
//
// Writes, under build/web/video/:
//   c11-hydrogen.<lang>.mp4, c11-hydrogen.<lang>.vtt,
//   c11-hydrogen.<lang>.still-first.png, c11-hydrogen.<lang>.still-middle.png,
//   c11-hydrogen.json (renderer string, flags, measured times per frame, frame counts, storyboard hash)
// With --ground dark the names carry ".dark" before the extension.
// The capture tool has no option for demo parameters, so the tour is switched on through
// data-params of the standalone page (web/video/c11-standalone.ts --params).
import { execFileSync } from 'node:child_process';
import crypto from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';
import { REPO_ROOT } from '../tools/convert/env.ts';

const args = process.argv.slice(2);
const opt = (n: string, d: string) => { const i = args.indexOf(n); return i >= 0 ? args[i + 1] : d; };
const langs = opt('--lang', 'de,en').split(',');
const ground = opt('--ground', 'light');
const gl = opt('--gl', 'swiftshader');
const pkg = opt('--pkg', '1');
const size = opt('--size', '');
const HERE = path.dirname(new URL(import.meta.url).pathname);
const TSX = path.join(HERE, '../node_modules/.bin/tsx');
const out = path.join(REPO_ROOT, 'build/web/video');
const sbFile = path.join(HERE, 'c11-hydrogen.storyboard.json');
const sbText = fs.readFileSync(sbFile, 'utf8');
const sb = JSON.parse(sbText) as { id: string; demo: string; scenes: Array<{ id: string; seconds: number; refs: string[]; caption: Record<string, string> }> };
fs.mkdirSync(out, { recursive: true });

// frames per second: the design tokens (video.fps), as the harness and the capture tool use it
const tokens = JSON.parse(fs.readFileSync(path.join(REPO_ROOT, `design/build/pkg${pkg}-light/tokens.json`), 'utf8')) as { video: { fps: number; width: number; height: number } };
const fps = tokens.video.fps;
const frames = sb.scenes.map((s) => Math.round(s.seconds * fps));
const total = frames.reduce((a, b) => a + b, 0);
const suffix = ground === 'dark' ? '.dark' : '';

// every caption must name what it rests on
for (const s of sb.scenes) {
  if (!s.refs?.length) throw new Error(`c11-video: scene ${s.id} has no refs`);
  for (const l of langs) if (!s.caption[l]) throw new Error(`c11-video: scene ${s.id} has no caption in ${l}`);
}
// claim IDs must exist in the chapter, when the chapter is there
const chapterTex = path.join(REPO_ROOT, 'content/c11-wasserstoff/de.tex');
if (fs.existsSync(chapterTex)) {
  const tex = fs.readFileSync(chapterTex, 'utf8');
  for (const s of sb.scenes) for (const r of s.refs) {
    if (r.startsWith('c11.cl.') && !tex.includes(`{${r}}`)) throw new Error(`c11-video: scene ${s.id} refers to claim ${r}, which content/c11-wasserstoff/de.tex does not declare`);
  }
}

const stamp = (frame: number) => {
  const ms = Math.round((frame / fps) * 1000);
  const p = (v: number, n = 2) => String(v).padStart(n, '0');
  return `${p(Math.floor(ms / 3600000))}:${p(Math.floor(ms / 60000) % 60)}:${p(Math.floor(ms / 1000) % 60)}.${p(ms % 1000, 3)}`;
};
for (const lang of langs) {
  let vtt = `WEBVTT\n\nNOTE\nGenerated by web/video/c11-video.ts from web/video/c11-hydrogen.storyboard.json (${lang}). Do not edit.\n`;
  let f = 0;
  sb.scenes.forEach((s, i) => {
    vtt += `\nNOTE ${s.id}: ${s.refs.join('; ')}\n\n${i + 1}\n${stamp(f)} --> ${stamp(f + frames[i])}\n${s.caption[lang]}\n`;
    f += frames[i];
  });
  fs.writeFileSync(path.join(out, `${sb.id}.${lang}.vtt`), vtt);
  console.log(`c11-video: wrote build/web/video/${sb.id}.${lang}.vtt (${sb.scenes.length} cues, ${stamp(total)})`);
}
if (args.includes('--vtt-only')) process.exit(0);

// standalone pages with the tour switched on
const standalone = path.join(out, 'standalone');
execFileSync(TSX, [path.join(HERE, 'c11-standalone.ts'), '--pkg', pkg, '--out', standalone, '--only', sb.demo, '--params', JSON.stringify({ tour: sb.id })], { stdio: 'inherit' });

const record: Record<string, unknown> = {
  storyboard: 'web/video/c11-hydrogen.storyboard.json', storyboard_sha256: crypto.createHash('sha256').update(sbText).digest('hex'),
  fps, frames_per_scene: Object.fromEntries(sb.scenes.map((s, i) => [s.id, frames[i]])), frames: total, ground, pkg: Number(pkg), runs: {} as Record<string, unknown>,
};
for (const lang of langs) {
  const cap = path.join(out, `capture-${lang}${suffix}`);
  const a = ['--demo', sb.demo, '--lang', lang, '--frames', String(total), '--gl', gl, '--ground', ground, '--standalone', standalone, '--out', cap];
  if (size) a.push('--size', size);
  execFileSync(TSX, [path.join(HERE, '../tools/capture/capture.ts'), ...a], { stdio: 'inherit' });
  const cj = JSON.parse(fs.readFileSync(path.join(cap, 'capture.json'), 'utf8')) as { renderer: Record<string, unknown>; measured_ms: Record<string, number>; flags: string[]; chromium: string; distinctFrames: number; deterministic: boolean; mp4: Record<string, unknown>; size: string; problems: string[] };
  const base = path.join(out, `${sb.id}.${lang}${suffix}`);
  fs.copyFileSync(path.join(cap, `${sb.demo}.mp4`), `${base}.mp4`);
  const middle = frames[0] + frames[1] + frames[2] + frames[3] + Math.floor(frames[4] / 2);   // the middle of the phase scene
  fs.copyFileSync(path.join(cap, 'frames', 'frame-00000.png'), `${base}.still-first.png`);
  fs.copyFileSync(path.join(cap, 'frames', `frame-${String(middle).padStart(5, '0')}.png`), `${base}.still-middle.png`);
  (record.runs as Record<string, unknown>)[lang] = {
    mp4: path.relative(REPO_ROOT, `${base}.mp4`), bytes: fs.statSync(`${base}.mp4`).size, vtt: `build/web/video/${sb.id}.${lang}.vtt`,
    stills: { first: 0, middle }, size: cj.size, chromium: cj.chromium, gl, flags: cj.flags,
    renderer: cj.renderer.renderer, webgl: cj.renderer.webgl, three: cj.renderer.three, points: cj.renderer.points,
    measured_ms: cj.measured_ms, distinct_frames: cj.distinctFrames, deterministic: cj.deterministic, mp4_stream: cj.mp4, problems: cj.problems,
  };
  console.log(`c11-video: ${path.relative(REPO_ROOT, base)}.mp4 (${total} frames at ${fps}/s), stills at frames 0 and ${middle}`);
}
fs.writeFileSync(path.join(out, `${sb.id}${suffix}.json`), JSON.stringify(record, null, 1));
console.log(`c11-video: wrote build/web/video/${sb.id}${suffix}.json`);
