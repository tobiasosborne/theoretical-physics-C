// Generated inputs of the bundles, written to build/web/gen/ (alias @gen):
//   labels.json  symbol ID -> bilingual name, Unicode and MathML, from the notation registry
//   video.json   width, height, fps of the video frame, from the design tokens
//   temml.css    Temml's stylesheet for its MathML classes, without its font rules
//                (the maths face is the token --tpc-font-math)
import fs from 'node:fs';
import path from 'node:path';
import { createRequire } from 'node:module';
import type { Paths } from '../convert/env.ts';

/** Top-level rules of a stylesheet, split by brace depth (comments kept with the next rule). */
function cssRules(css: string): string[] {
  const rules: string[] = [];
  let depth = 0, start = 0, inComment = false;
  for (let i = 0; i < css.length; i++) {
    if (inComment) { if (css.startsWith('*/', i)) { inComment = false; i++; } continue; }
    if (css.startsWith('/*', i)) { inComment = true; i++; continue; }
    if (css[i] === '{') depth++;
    else if (css[i] === '}') { depth--; if (depth === 0) { rules.push(css.slice(start, i + 1)); start = i + 1; } }
  }
  return rules;
}

export function writeGen(paths: Paths, pkg: number, ground: string): string {
  const gen = path.join(paths.root, 'build/web/gen');
  fs.mkdirSync(gen, { recursive: true });
  const notation = JSON.parse(fs.readFileSync(path.join(paths.root, 'registry/generated/notation.web.json'), 'utf8')) as {
    symbols: Array<{ symbol_id: string; name: { de: string; en: string }; unicode: string; mathml: string }>;
  };
  const labels: Record<string, unknown> = {};
  for (const s of notation.symbols) labels[s.symbol_id] = { de: s.name.de, en: s.name.en, unicode: s.unicode, mathml: s.mathml };
  fs.writeFileSync(path.join(gen, 'labels.json'), JSON.stringify(labels));
  const tokens = JSON.parse(fs.readFileSync(path.join(paths.design, `pkg${pkg}-${ground}`, 'tokens.json'), 'utf8')) as { video: { width: number; height: number; fps: number } };
  fs.writeFileSync(path.join(gen, 'video.json'), JSON.stringify({ width: tokens.video.width, height: tokens.video.height, fps: tokens.video.fps }));

  const require = createRequire(import.meta.url);
  const src = fs.readFileSync(require.resolve('temml/dist/Temml-STIX2.css'), 'utf8');
  const kept = cssRules(src).filter((r) => {
    const head = r.slice(0, r.indexOf('{'));
    const sel = head.slice(head.lastIndexOf('*/') + 1).replace(/^\/?\s*/, '').trim();
    if (sel.startsWith('@font-face')) return false;                       // no font files from Temml
    if (sel === 'math' && /font-family\s*:/.test(r) && !/font-style/.test(r)) return false;   // the face is a token
    if (sel === 'body' || sel.startsWith('.tml-eqn')) return false;       // numbers come from print, not from a CSS counter
    return true;
  }).map((r) => r.replace(/\/\*[\s\S]*?\*\//g, '').trim());
  fs.writeFileSync(path.join(gen, 'temml.css'),
    `/* Temml ${JSON.parse(fs.readFileSync(require.resolve('temml/package.json'), 'utf8')).version} stylesheet (MIT), dist/Temml-STIX2.css, without its @font-face, font-family and counter rules. GENERATED by web/tools/build/gen.ts. */\n`
    + kept.join('\n') + '\n');
  return gen;
}
