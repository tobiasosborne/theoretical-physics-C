#!/usr/bin/env python3
"""Collect the open fonts of fonts=open into web/assets/fonts/ as WOFF2.

    python3 web/tools/fonts/collect_fonts.py            # write web/assets/fonts/
    python3 web/tools/fonts/collect_fonts.py --check    # gate: files match the manifest

A family is bundled ONLY IF its SIL OFL licence text is found on this machine next to
the font's documentation; the licence is copied beside the fonts. A family without a
licence file is skipped and listed under "skipped" in manifest.json (the CSS stack then
falls through to the generic family). No commercial face is ever looked for: the list
below names open families only (PLAN D10, COORDINATION rule 5).

Output: <family files>.woff2, LICENSES/<key>-OFL.txt, manifest.json (source path and
sha256 of every input and output), fonts.css (@font-face rules; the family names are
those of the token stacks in design/build/*/tokens.css).
"""
import argparse
import gzip
import hashlib
import json
import pathlib
import subprocess
import sys

HERE = pathlib.Path(__file__).resolve()
OUT = HERE.parents[2] / "assets" / "fonts"

# family key -> (CSS family, licence candidates, faces: (file, weight, style))
FAMILIES = {
    "stix-two-text": ("STIX Two Text", ["doc/fonts/stix2-otf/OFL.txt.gz", "doc/fonts/stix2-otf/OFL.txt"], [
        ("STIXTwoText-Regular.otf", 400, "normal"), ("STIXTwoText-Italic.otf", 400, "italic"),
        ("STIXTwoText-SemiBold.otf", 600, "normal"), ("STIXTwoText-SemiBoldItalic.otf", 600, "italic"),
        ("STIXTwoText-Bold.otf", 700, "normal"), ("STIXTwoText-BoldItalic.otf", 700, "italic")]),
    "stix-two-math": ("STIX Two Math", ["doc/fonts/stix2-otf/OFL.txt.gz", "doc/fonts/stix2-otf/OFL.txt"], [
        ("STIXTwoMath-Regular.otf", 400, "normal")]),
    "inter": ("Inter", ["doc/fonts/inter/LICENSE.txt.gz", "doc/fonts/inter/LICENSE.txt"], [
        ("Inter-Regular.otf", 400, "normal"), ("Inter-Italic.otf", 400, "italic"),
        ("Inter-SemiBold.otf", 600, "normal"), ("Inter-SemiBoldItalic.otf", 600, "italic")]),
    "libertinus-serif": ("Libertinus Serif", ["doc/fonts/libertinus-fonts/OFL.txt.gz", "doc/fonts/libertinus-fonts/OFL.txt"], [
        ("LibertinusSerif-Regular.otf", 400, "normal"), ("LibertinusSerif-Italic.otf", 400, "italic"),
        ("LibertinusSerif-Semibold.otf", 600, "normal"), ("LibertinusSerif-SemiboldItalic.otf", 600, "italic"),
        ("LibertinusSerif-Bold.otf", 700, "normal"), ("LibertinusSerif-BoldItalic.otf", 700, "italic")]),
    "libertinus-sans": ("Libertinus Sans", ["doc/fonts/libertinus-fonts/OFL.txt.gz", "doc/fonts/libertinus-fonts/OFL.txt"], [
        ("LibertinusSans-Regular.otf", 400, "normal"), ("LibertinusSans-Italic.otf", 400, "italic"),
        ("LibertinusSans-Bold.otf", 700, "normal")]),
    "libertinus-mono": ("Libertinus Mono", ["doc/fonts/libertinus-fonts/OFL.txt.gz", "doc/fonts/libertinus-fonts/OFL.txt"], [
        ("LibertinusMono-Regular.otf", 400, "normal")]),
    "libertinus-math": ("Libertinus Math", ["doc/fonts/libertinus-fonts/OFL.txt.gz", "doc/fonts/libertinus-fonts/OFL.txt"], [
        ("LibertinusMath-Regular.otf", 400, "normal")]),
    # Iosevka is installed through fontconfig (/usr/local/share/fonts/iosevka) without a
    # licence file beside it: looked for, and skipped unless one appears.
    "iosevka": ("Iosevka", ["__none__"], []),
}
OFL_MARK = "SIL Open Font License"


def sha(path):
    return hashlib.sha256(pathlib.Path(path).read_bytes()).hexdigest()


def kpse(name):
    r = subprocess.run(["kpsewhich", name], capture_output=True, text=True)
    return r.stdout.strip() or None


def texmf_dist():
    p = kpse("STIXTwoMath-Regular.otf") or kpse("article.cls")
    if not p:
        return None
    q = pathlib.Path(p)
    for parent in q.parents:
        if parent.name == "texmf-dist":
            return parent
    return None


def read_licence(dist, candidates):
    for c in candidates:
        p = dist / c if dist else None
        if p and p.is_file():
            data = p.read_bytes()
            text = gzip.decompress(data).decode("utf-8") if p.suffix == ".gz" else data.decode("utf-8")
            if OFL_MARK in text:
                return p, text
    return None, None


def build():
    from fontTools.ttLib import TTFont
    dist = texmf_dist()
    OUT.mkdir(parents=True, exist_ok=True)
    (OUT / "LICENSES").mkdir(exist_ok=True)
    manifest = {"note": "Generated by web/tools/fonts/collect_fonts.py. Open fonts only (SIL OFL 1.1).",
                "families": {}, "skipped": {}}
    css = ["/* fonts.css: GENERATED by web/tools/fonts/collect_fonts.py. Open fonts (SIL OFL 1.1) only;",
           "   licences in LICENSES/. Family names are those of the token stacks. */"]
    for key, (family, lic_candidates, faces) in FAMILIES.items():
        lic_path, lic_text = read_licence(dist, lic_candidates)
        if lic_path is None:
            manifest["skipped"][key] = {"family": family, "reason": "no SIL OFL licence file found on this machine"}
            print(f"skip   {family}: no licence file")
            continue
        lic_out = OUT / "LICENSES" / f"{key}-OFL.txt"
        lic_out.write_text(lic_text, encoding="utf-8")
        entry = {"family": family, "licence": "SIL OFL 1.1", "licence_source": str(lic_path),
                 "licence_file": f"LICENSES/{key}-OFL.txt", "faces": []}
        for fname, weight, style in faces:
            src = kpse(fname)
            if not src:
                print(f"error  {fname}: not found by kpsewhich", file=sys.stderr)
                return 1
            out = OUT / (pathlib.Path(fname).stem + ".woff2")
            font = TTFont(src)
            font.flavor = "woff2"
            font.save(out)
            entry["faces"].append({"file": out.name, "weight": weight, "style": style, "source": src,
                                   "source_sha256": sha(src), "bytes": out.stat().st_size})
            css.append(f'@font-face {{ font-family: "{family}"; font-weight: {weight}; font-style: {style}; '
                       f'font-display: swap; src: url("./{out.name}") format("woff2"); }}')
            print(f"ok     {out.name}  {out.stat().st_size // 1024} KiB  <- {src}")
        manifest["families"][key] = entry
    (OUT / "fonts.css").write_text("\n".join(css) + "\n", encoding="utf-8")
    (OUT / "manifest.json").write_text(json.dumps(manifest, indent=1, ensure_ascii=False) + "\n", encoding="utf-8")
    return 0


def check():
    mf = OUT / "manifest.json"
    if not mf.is_file():
        print(f"fonts: FAIL: {mf} missing; run web/tools/fonts/collect_fonts.py")
        return 1
    manifest = json.loads(mf.read_text())
    bad = 0
    listed = {"fonts.css", "manifest.json"}
    for key, fam in manifest["families"].items():
        lic = OUT / fam["licence_file"]
        if not lic.is_file() or OFL_MARK not in lic.read_text(encoding="utf-8"):
            print(f"fonts: FAIL: {fam['family']}: licence file {lic} missing or not the SIL OFL")
            bad += 1
        for face in fam["faces"]:
            listed.add(face["file"])
            if not (OUT / face["file"]).is_file():
                print(f"fonts: FAIL: {face['file']} listed in the manifest but missing")
                bad += 1
    for f in OUT.iterdir():
        if f.is_file() and f.name not in listed:
            print(f"fonts: FAIL: {f.name} is in web/assets/fonts/ but not in the manifest (no licence record)")
            bad += 1
    if bad == 0:
        n = sum(len(f["faces"]) for f in manifest["families"].values())
        print(f"fonts: ok: {n} faces in {len(manifest['families'])} open families, each with its OFL text; "
              f"skipped: {', '.join(manifest['skipped']) or 'none'}")
    return 1 if bad else 0


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    sys.exit(check() if args.check else build())
