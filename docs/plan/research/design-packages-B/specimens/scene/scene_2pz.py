r"""PKG-5 'one scene, three views' demonstrator (design-packages-B lane, 2026-10-09).

One scene description (camera + objects with physics roles + labels) for the hydrogen 2p_z
(n=2, l=1, m=0) density, emitted twice from the same projected coordinates:
  scene_2pz.tikz  -> \input by pkg5.tex (print frame)
  scene_2pz.svg.txt -> pasted into pkg5.html (screen frame)
  scene_2pz.json  -> the scene graph itself (what three.js would load)
Physics (atomic units a0 = 1, Z = 1):
  psi_210 = (4 sqrt(2 pi))^{-1} r e^{-r/2} cos(theta),  |psi|^2 = (32 pi)^{-1} r^2 e^{-r} cos^2(theta).
  Maximum on the z axis at r = 2. The f-contour  r^2 e^{-r} cos^2 = f * 4 e^{-2}  exists for
  cos^2(theta) >= f, i.e. |theta| <= arccos(sqrt f)  (45 degrees for f = 1/2).
The script also integrates the probability inside the f-contour (both lobes) and checks the
normalisation of |psi|^2 numerically.
"""
import math, json, os
HERE = os.path.dirname(os.path.abspath(__file__))
F = 0.5                      # contour level as a fraction of the maximum density
PHI, EL = 35.0, 20.0         # camera azimuth / elevation in degrees, orthographic (view 'V1')
MM = 6.0                     # print scale: mm per Bohr radius
g = lambda r: r*r*math.exp(-r)
c = F*4*math.exp(-2)

def roots(th):
    k = c/math.cos(th)**2
    if k > g(2): return None
    def bis(lo, hi, inc):
        for _ in range(80):
            mid = 0.5*(lo+hi)
            if (g(mid) < k) == inc: lo = mid
            else: hi = mid
        return 0.5*(lo+hi)
    return bis(1e-9, 2, True), bis(2, 60, False)

thmax = math.acos(math.sqrt(F))
N = 60
ths = [-thmax + 2*thmax*i/N for i in range(N+1)]
ths[0] += 1e-9; ths[-1] -= 1e-9
outer = [roots(t)[1] for t in ths]; inner = [roots(t)[0] for t in ths]
# closed lobe in the y = 0 slice: outer arc then inner arc back
lobe_up = [(r*math.sin(t), 0.0, r*math.cos(t)) for r, t in zip(outer, ths)] + \
          [(r*math.sin(t), 0.0, r*math.cos(t)) for r, t in reversed(list(zip(inner, ths)))]
lobe_dn = [(x, y, -z) for (x, y, z) in lobe_up]

def proj(p):
    x, y, z = p; ph, el = math.radians(PHI), math.radians(EL)
    return (-x*math.sin(ph) + y*math.cos(ph), z*math.cos(el) - (x*math.cos(ph) + y*math.sin(ph))*math.sin(el))

S = 3.6
plane = [(-S, -S, 0), (S, -S, 0), (S, S, 0), (-S, S, 0)]
zaxis = [(0, 0, -5.2), (0, 0, 5.2)]
gizmo_o = (4.5, -4.5, -4.6)  # world position of the gizmo origin (projects to the lower left)

# probability inside the contour (both lobes), and total, by midpoint rule in (r, theta)
def prob(inside_only=True):
    tot = 0.0; nr, nt = 3000, 600; rmax = 40.0
    for j in range(nt):
        t = (j+0.5)*math.pi/nt
        for i in range(nr):
            r = (i+0.5)*rmax/nr
            if inside_only and g(r)*math.cos(t)**2 < c: continue
            tot += r*r*math.exp(-r)*math.cos(t)**2/(32*math.pi) * 2*math.pi*r*r*math.sin(t)
    return tot*(rmax/nr)*(math.pi/nt)
P_in, P_tot = prob(True), prob(False)

scene = {
 'id': 'F-16.2', 'title': {'de': 'Wasserstoff 2p_z: Kontur halber Maximaldichte', 'en': 'Hydrogen 2p_z: half-maximum contour'},
 'camera': {'type': 'orthographic', 'view': 'V1', 'azimuth_deg': PHI, 'elevation_deg': EL, 'up': 'z'},
 'units': {'length': 'a0', 'print_mm_per_unit': MM},
 'objects': [
  {'id': 'nodal-plane', 'role': 'state', 'kind': 'plane', 'z': 0, 'half_width': S, 'style': 'dashed-outline+tint'},
  {'id': 'lobe+', 'role': 'state', 'kind': 'contour-slice', 'field': '|psi_210|^2', 'level_fraction': F, 'slice': 'y=0'},
  {'id': 'lobe-', 'role': 'state', 'kind': 'contour-slice', 'field': '|psi_210|^2', 'level_fraction': F, 'slice': 'y=0'},
  {'id': 'z-axis', 'role': 'ink', 'kind': 'axis'},
  {'id': 'gizmo', 'role': 'ink', 'kind': 'axis-gizmo', 'anchor': 'lower-left'}],
 'labels': [{'target': 'lobe+', 'text': {'de': '|ψ₂₁₀|² = ½ max', 'en': '|ψ₂₁₀|² = ½ max'}, 'side': 'right'},
            {'target': 'nodal-plane', 'text': {'de': 'Knotenebene z = 0', 'en': 'nodal plane z = 0'}, 'side': 'right'}],
 'readouts': {'P_inside_contour': round(P_in, 4), 'P_total_check': round(P_tot, 4)},
}
json.dump(scene, open(os.path.join(HERE, 'scene_2pz.json'), 'w'), indent=1, ensure_ascii=False)

def pts(ps): return [proj(p) for p in ps]
# ---------- TikZ (mm)
def tz(ps): return ' -- '.join(f'({X*MM:.2f}mm,{Y*MM:.2f}mm)' for X, Y in pts(ps))
o = gizmo_o; L = 2.0
gx, gy, gz = [(o[0]+L*a, o[1]+L*b, o[2]+L*cc) for a, b, cc in ((1,0,0),(0,1,0),(0,0,1))]
top = max(pts(lobe_up), key=lambda q: q[0])  # rightmost point of upper lobe
lab_lobe = proj((0, 0, 0)); 
tikz = [r'% GENERATED by scene_2pz.py from the scene graph; do not edit.',
 r'\begin{tikzpicture}[font=\sffamily\footnotesize]',
 rf'\fill[tpc-state,opacity=0.18] {tz(lobe_dn)} -- cycle;',
 rf'\draw[tpc-state,line width=1.0pt] {tz(lobe_dn)} -- cycle;',
 rf'\fill[tpc-state,opacity=0.06] {tz(plane)} -- cycle;',
 rf'\draw[tpc-state,line width=0.5pt,dash pattern=on 2pt off 1.5pt] {tz(plane)} -- cycle;',
 rf'\draw[tpc-ink,line width=0.4pt] {tz(zaxis)};',
 rf'\fill[tpc-state,opacity=0.18] {tz(lobe_up)} -- cycle;',
 rf'\draw[tpc-state,line width=1.0pt] {tz(lobe_up)} -- cycle;',
 rf'\fill[tpc-ink] ({0:.2f}mm,{0:.2f}mm) circle (0.6pt);',
]
# direct labels with leaders (screen space, outside the object)
ax, ay = top; tikz.append(rf'\draw[tpc-ink,line width=0.3pt] ({ax*MM:.2f}mm,{ay*MM:.2f}mm) -- ({ax*MM+9:.2f}mm,{ay*MM+6:.2f}mm) node[anchor=west,text=tpc-state,inner sep=1pt] {{$\lvert\psi_{{210}}\rvert^2=\tfrac12\max$}};')
pc = proj((-S, S, 0)); tikz.append(rf'\draw[tpc-ink,line width=0.3pt] ({pc[0]*MM:.2f}mm,{pc[1]*MM:.2f}mm) -- ({pc[0]*MM+5:.2f}mm,{pc[1]*MM-4:.2f}mm) node[anchor=west,text=tpc-ink,inner sep=1pt] {{Knotenebene $z=0$}};')
for v, name in ((gx, 'x'), (gy, 'y'), (gz, 'z')):
    a, b = proj(o); X, Y = proj(v)
    tikz.append(rf'\draw[tpc-ink,line width=0.5pt,-{{Stealth[length=3pt]}}] ({a*MM:.2f}mm,{b*MM:.2f}mm) -- ({X*MM:.2f}mm,{Y*MM:.2f}mm) node[pos=1.25,inner sep=0pt,font=\footnotesize] {{${name}$}};')
tikz.append(r'\end{tikzpicture}')
open(os.path.join(HERE, 'scene_2pz.tikz'), 'w').write('\n'.join(tikz) + '\n')

# ---------- SVG (px, y down); same projected points, 1 a0 = 18 px
PX = 18.0
def sv(ps): return ' '.join(f'{X*PX:.1f},{-Y*PX:.1f}' for X, Y in pts(ps))
a, b = proj(o)
svg = [f'<polygon class="r-state-fill" points="{sv(lobe_dn)}"/><polygon class="r-state" points="{sv(lobe_dn)}"/>',
       f'<polygon class="r-state-plane" points="{sv(plane)}"/>',
       f'<polyline class="r-ink thin" points="{sv(zaxis)}"/>',
       f'<polygon class="r-state-fill" points="{sv(lobe_up)}"/><polygon class="r-state" points="{sv(lobe_up)}"/>']
for v, name in ((gx, 'x'), (gy, 'y'), (gz, 'z')):
    X, Y = proj(v); tx, ty = a + 1.3*(X-a), b + 1.3*(Y-b)
    svg.append(f'<line class="r-ink gizmo" x1="{a*PX:.1f}" y1="{-b*PX:.1f}" x2="{X*PX:.1f}" y2="{-Y*PX:.1f}" marker-end="url(#arr)"/>'
               f'<text class="gizmo-l" x="{tx*PX:.1f}" y="{-ty*PX:.1f}">{name}</text>')
svg.append(f'<line class="r-ink leader" x1="{ax*PX:.1f}" y1="{-ay*PX:.1f}" x2="{ax*PX+27:.1f}" y2="{-ay*PX-18:.1f}"/>'
           f'<text class="lab r-state-text" x="{ax*PX+30:.1f}" y="{-ay*PX-18:.1f}">|ψ<tspan baseline-shift="sub" font-size="70%">210</tspan>|² = ½ <tspan font-style="normal">max</tspan></text>')
svg.append(f'<line class="r-ink leader" x1="{pc[0]*PX:.1f}" y1="{-pc[1]*PX:.1f}" x2="{pc[0]*PX+15:.1f}" y2="{-pc[1]*PX+12:.1f}"/>'
           f'<text class="lab" x="{pc[0]*PX+18:.1f}" y="{-pc[1]*PX+16:.1f}">Knotenebene z = 0</text>')
allp = pts(lobe_up + lobe_dn + plane + zaxis + [gx, gy, gz, o])
xs = [p[0]*PX for p in allp]; ys = [-p[1]*PX for p in allp]
vb = (min(xs)-150, min(ys)-30, max(xs)-min(xs)+330, max(ys)-min(ys)+70)
open(os.path.join(HERE, 'scene_2pz.svg.txt'), 'w').write(f'viewBox="{vb[0]:.0f} {vb[1]:.0f} {vb[2]:.0f} {vb[3]:.0f}"\n' + '\n'.join(svg) + '\n')
print(f'theta_max = {math.degrees(thmax):.2f} deg, outer r on axis = {roots(1e-12)[1]:.4f}, inner = {roots(1e-12)[0]:.4f}')
print(f'P inside half-max contour = {P_in:.4f}; normalisation check = {P_tot:.4f}')
